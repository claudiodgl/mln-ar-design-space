"""Generate LaTeX tables and the corpus figure for the supplement from the review outputs.

Usage: python -I -X utf8 scripts/build_supplement_tables.py <supplement_dir>
Writes tables/screening_rounds.tex, tables/fulltext_numbers.tex,
tables/benchmark.tex and tables/corpus_years.tex (a TikZ bar chart, so no
plotting library is needed); prints the numbers used.
"""
from __future__ import annotations

import collections
import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "output"
SUP = Path(sys.argv[1])
(SUP / "tables").mkdir(parents=True, exist_ok=True)

# (label, screening sheet); the IEEE Xplore search was run after snowballing and
# de-duplicated against all earlier records (scripts/merge_ieee_incremental.py)
ROUNDS = [("R1", "screening.csv"), ("R2", "screening_R2.csv"), ("R3", "screening_R3.csv"),
          ("R4", "screening_R4.csv"), ("R5", "screening_R5.csv"), ("IEEE", "screening_IEEE_new.csv")]


def rows(fn):
    return list(csv.DictReader(open(OUT / fn, encoding="utf-8-sig")))


def eff(r):
    return (r.get("A1_decision") or r.get("final_decision") or r.get("AI_decision") or "").strip()


def code(r):
    return (r.get("A1_code") or r.get("AI_code") or "").strip()


def esc(s):
    return (s or "").replace("&", r"\&").replace("%", r"\%").replace("_", r"\_").replace("#", r"\#")


def fmt(n):
    return f"{n:,}".replace(",", "{,}") if isinstance(n, int) else n


# ------------------------------------------------------------- screening per round
new_counts = {"R1": None, "R2": 11275 + 2217, "R3": 3301, "R4": 351, "R5": 11, "IEEE": None}
seeds = {"R1": "5 surveys", "R2": "363", "R3": "194", "R4": "29", "R5": "2", "IEEE": "--"}
direction = {"R1": "backward + forward", "R2": "backward + forward", "R3": "backward", "R4": "backward",
             "R5": "backward", "IEEE": "database search"}
label = {"R1": "Search + R1", "IEEE": "IEEE Xplore"}
lines, tot = [], collections.Counter()
for rd, fn in ROUNDS:
    rs = rows(fn)
    c = collections.Counter(eff(r) for r in rs)
    n_new = new_counts[rd] if new_counts[rd] else (len(rs) if rd == "IEEE" else None)
    e0 = (n_new - len(rs)) if n_new else 0
    tot.update({"screened": len(rs), "e0": e0, **c})
    lines.append(f"{label.get(rd, rd)} & {seeds[rd]} & {direction[rd]} & {fmt(n_new) if n_new else '--'} & "
                 f"{fmt(e0) if new_counts[rd] else '--'} & {fmt(len(rs))} & {c['include']} & {c['background']} & "
                 f"{c['unsure']} & {fmt(c['exclude'])} \\\\")
lines.append(r"\midrule")
lines.append(f"Total & & & & {fmt(tot['e0'])} & {fmt(tot['screened'])} & {tot['include']} & {tot['background']} & "
             f"{tot['unsure']} & {fmt(tot['exclude'])} \\\\")
(SUP / "tables" / "screening_rounds.tex").write_text(
    "% generated by scripts/build_supplement_tables.py\n"
    "\\begin{tabular}{llrrrrrrrr}\n\\toprule\n"
    "Round & Seeds & Direction & New records & Keyword rule (E0) & Screened & Include & Background & Unsure & Exclude \\\\\n\\midrule\n"
    + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}\n", encoding="utf-8")
print("screening totals", dict(tot))

# ------------------------------------------------------------- full-text stage
ft = rows("fulltext_results.csv")
fc = collections.Counter(r["ft_decision"] for r in ft)
fcodes = collections.Counter(r["ft_code"] for r in ft if r["ft_decision"] == "exclude")
retrieved = [r for r in ft if r["ft_decision"] != "not_retrieved"]
on_fulltext = sum(r["ft_stage"] == "fulltext" for r in retrieved)
likely = sum(r["ft_decision"] == "not_retrieved" and "likely include" in (r.get("ft_note") or "") for r in ft)
assert fc["needs_fulltext"] == 0, "full-text stage not finished"
print("fulltext", dict(fc), dict(fcodes), "assessed on full text", on_fulltext, "not retrieved, likely include", likely)
(SUP / "tables" / "fulltext_numbers.tex").write_text(
    "% generated by scripts/build_supplement_tables.py\n"
    f"\\newcommand{{\\FTpool}}{{{fmt(len(ft))}}}\n\\newcommand{{\\FTinc}}{{{fc['include']}}}\n"
    f"\\newcommand{{\\FTbg}}{{{fc['background']}}}\n\\newcommand{{\\FTexc}}{{{fc['exclude']}}}\n"
    f"\\newcommand{{\\FTnotret}}{{{fc['not_retrieved']}}}\n\\newcommand{{\\FTlikely}}{{{likely}}}\n"
    f"\\newcommand{{\\FTretrieved}}{{{len(retrieved)}}}\n\\newcommand{{\\FTonfulltext}}{{{on_fulltext}}}\n"
    f"\\newcommand{{\\FTonabstract}}{{{len(retrieved) - on_fulltext}}}\n"
    f"\\newcommand{{\\TAinc}}{{{tot['include']}}}\n\\newcommand{{\\TAscreened}}{{{fmt(tot['screened'])}}}\n"
    f"\\newcommand{{\\TAbg}}{{{tot['background']}}}\n\\newcommand{{\\TAexc}}{{{fmt(tot['exclude'])}}}\n"
    f"\\newcommand{{\\EzeroExc}}{{{fmt(tot['e0'])}}}\n"
    f"\\newcommand{{\\CorpusInc}}{{{tot['include'] + fc['include']}}}\n"
    f"\\newcommand{{\\CorpusBg}}{{{tot['background'] + fc['background']}}}\n", encoding="utf-8")

# ------------------------------------------------------------- benchmark retrieval per work
SRC = {"openalex": "OA", "s2": "S2", "dblp": "DBLP", "egdl": "EGDL", "arxiv": "arXiv", "acm": "ACM", "ieee": "IEEE"}
bench = {b["bid"]: b for b in csv.DictReader(open(ROOT / "config" / "benchmark.csv", encoding="utf-8-sig"))}
lines = []
for r in csv.DictReader(open(OUT / "benchmark_recall.csv", encoding="utf-8-sig")):
    if r["bid"] not in bench:
        continue
    byq = collections.defaultdict(set)
    for tok in filter(None, (x.strip() for x in r["retrieved_by_search"].split(";"))):
        s, q = tok.split(":", 1)
        byq[q.split("_")[0]].add(SRC.get(s, s))
    srch = "; ".join(f"{q}: {', '.join(sorted(v))}" for q, v in sorted(byq.items())) or "--"
    toks = [t.strip() for t in r["retrieved_by_snowballing"].split(";") if t.strip()]
    rds = sorted({t.split(":")[0] for t in toks})
    s1 = sorted({t.split(":")[1] for t in toks if t.startswith("R1:")})
    snow = ", ".join(rds) + (f" (R1 seeds {', '.join(s1)})" if s1 else "") if rds else "--"
    crit = re.sub(r"\s*\([^)]*\)", "", r["proposed_criterion"]).replace(" ", "")   # codes only, e.g. I1/I5
    lines.append(f"{esc(r['work'])} & {r['platform']} & {crit} & {srch} & {snow} \\\\")
(SUP / "tables" / "benchmark.tex").write_text(
    "% generated by scripts/build_supplement_tables.py (tabular body; float defined in supplement.tex)\n"
    "\\begin{tabular}{@{}p{3.0cm}p{1.2cm}p{0.8cm}p{6.6cm}p{4.2cm}@{}}\n"
    "\\toprule\nWork & Platform & Crit. & Database search (query: sources) & Snowballing rounds \\\\\n\\midrule\n"
    + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}\n", encoding="utf-8")

# ------------------------------------------------------------- corpus by year and criterion (TikZ figure)
inc = []
for rd, fn in ROUNDS:
    for r in rows(fn):
        if eff(r) == "include":
            inc.append((r.get("year", ""), code(r)[:2]))
for r in ft:
    if r["ft_decision"] == "include":
        inc.append((r.get("year", ""), (r["ft_code"] or "")[:2]))
bins = ["<2000", "2000--04", "2005--09", "2010--14", "2015--19", "2020--22", "2023--26"]


def b(y):
    try:
        y = int(float(y))
    except ValueError:
        return None
    for i, hi in enumerate((2000, 2005, 2010, 2015, 2020, 2023)):
        if y < hi:
            return bins[i]
    return bins[6]


cats = ["I1", "I2", "I3", "I4", "I5"]
names = {"I1": "I1 multilayer / layered dynamic", "I2": "I2 immersive network", "I3": "I3 physical / tangible network",
         "I4": "I4 AR visualization (abstract data)", "I5": "I5 representation building block"}
colors = ["0072B2", "E69F00", "009E73", "CC79A7", "56B4E9"]   # Okabe-Ito
cnt = {c: collections.Counter() for c in cats}
for y, c in inc:
    if c in cnt and b(y):
        cnt[c][b(y)] += 1
totals = [sum(cnt[c][x] for c in cats) for x in bins]
H, W, GAP = 3.4, 0.62, 0.95          # plot height (cm), bar width, bar spacing
ymax = max(totals) * 1.12
step = 25 if ymax < 200 else 50
t = ["% generated by scripts/build_supplement_tables.py",
     "\\begin{tikzpicture}[x=1cm,y=1cm,font=\\scriptsize]"]
for c, col in zip(cats, colors):
    t.append(f"\\definecolor{{cy{c}}}{{HTML}}{{{col}}}")
for v in range(0, int(ymax) + 1, step):
    yy = H * v / ymax
    t.append(f"\\draw[black!12,line width=0.3pt] (-0.15,{yy:.3f}) -- ({GAP * len(bins) - 0.3:.2f},{yy:.3f});")
    t.append(f"\\node[anchor=east,text=black!70] at (-0.15,{yy:.3f}) {{{v}}};")
t.append(f"\\node[rotate=90,anchor=south,text=black!70] at (-0.75,{H / 2:.2f}) {{Included works}};")
for i, x in enumerate(bins):
    cx, y0 = GAP * i + 0.3, 0.0
    for c in cats:
        n = cnt[c][x]
        if n:
            h = H * n / ymax
            t.append(f"\\fill[cy{c},draw=white,line width=0.4pt] ({cx - W / 2:.3f},{y0:.3f}) rectangle ({cx + W / 2:.3f},{y0 + h:.3f});")
            y0 += h
    t.append(f"\\node[anchor=south,text=black!75] at ({cx:.3f},{y0:.3f}) {{{totals[i]}}};")
    t.append(f"\\node[anchor=north,text=black!75] at ({cx:.3f},-0.02) {{{x.replace('<', '$<$')}}};")
t.append(f"\\draw[black!45,line width=0.4pt] (-0.15,0) -- ({GAP * len(bins) - 0.3:.2f},0);")
for k, (c, col) in enumerate(zip(cats, colors)):   # legend below the axis, two columns
    lx, ly = (0.0 if k < 3 else 3.5), -0.75 - 0.32 * (k % 3)
    t.append(f"\\fill[cy{c}] ({lx:.2f},{ly - 0.09:.2f}) rectangle ({lx + 0.2:.2f},{ly + 0.09:.2f}); "
             f"\\node[anchor=west] at ({lx + 0.22:.2f},{ly:.2f}) {{{names[c]}}};")
t.append("\\end{tikzpicture}")
(SUP / "tables" / "corpus_years.tex").write_text("\n".join(t) + "\n", encoding="utf-8")
print("figure: included works with year", sum(totals), "of", len(inc), dict(zip(bins, totals)))
